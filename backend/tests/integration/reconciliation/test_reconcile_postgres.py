def _rows(engine: Engine, sql: str, **params: object) -> list[tuple[object, ...]]:
    with engine.connect() as connection:
        return [tuple(r) for r in connection.execute(text(sql), params)]


@pytest.fixture
def loaded(engine: Engine, sample: Path) -> Engine:
    uow = SqlAlchemyIngestionUnitOfWork(sessionmaker(engine))
    ImportExport(uow, SystemClock(), UuidIdGenerator())(read_export(sample))
    with engine.begin() as connection:
        connection.execute(text(REFERENCE))
    return engine


def _reconcile(engine: Engine) -> ReconcilePeriod:
    uow = SqlAlchemyReconciliationUnitOfWork(sessionmaker(engine))
    return ReconcilePeriod(uow, SystemClock(), UuidIdGenerator())


def test_reconciling_the_sample_persists_every_discrepancy_group_and_event(loaded: Engine) -> None:
    run = _reconcile(loaded)(OCTOBER)

    assert run.status is RunStatus.COMPLETED
    [(status, period)] = _rows(loaded, "SELECT status, period::text FROM recon.reconciliation_runs")
    assert (status, period) == ("completed", "[2026-10-01,2026-11-01)")
    by_type = {
        t: n
        for t, n in _rows(loaded, "SELECT type, count(*) FROM recon.discrepancies GROUP BY type")
    }
    assert sum(int(str(n)) for n in by_type.values()) == 41
    assert by_type["missing_in_bank"] == 1 and by_type["duplicate_refund"] == 4
    assert _rows(
        loaded, "SELECT count(*) FROM recon.outbox WHERE event_type = 'DiscrepancyDetected'"
    ) == [(41,)]
    # delta is generated by the database from expected and actual
    assert _rows(
        loaded,
        "SELECT count(*) FROM recon.discrepancies d"
        " JOIN ref.discrepancy_types t ON t.code = d.type AND d.severity = t.default_severity"
        " WHERE d.delta_minor = d.actual_minor - d.expected_minor",
    ) == [(41,)]
    [(orders_linked,)] = _rows(
        loaded, "SELECT count(*) FROM recon.match_group_members WHERE order_id IS NOT NULL"
    )
    assert orders_linked == 158


def test_reconciling_again_returns_the_run_and_creates_nothing(loaded: Engine) -> None:
    first = _reconcile(loaded)(OCTOBER)
    counts = (
        "SELECT (SELECT count(*) FROM recon.match_groups),"
        " (SELECT count(*) FROM recon.discrepancies)"
    )
    fingerprints = "SELECT fingerprint FROM recon.discrepancies ORDER BY fingerprint"
    before = (_rows(loaded, counts), _rows(loaded, fingerprints))

    again = _reconcile(loaded)(OCTOBER)

    assert again == first
    assert (_rows(loaded, counts), _rows(loaded, fingerprints)) == before
    assert _rows(loaded, "SELECT count(*) FROM recon.reconciliation_runs") == [(1,)]


def test_a_run_failing_halfway_is_failed_with_no_groups_or_discrepancies(loaded: Engine) -> None:
    _reconcile(loaded)(OCTOBER)
    # A second ruleset on the same period finds the same fingerprints: the first discrepancy
    # insert fails after every match group of the run was written.
    with pytest.raises(IntegrityError, match="discrepancies_fingerprint_key"):
        _reconcile(loaded)(OCTOBER, "v2")

    [(run_id, status)] = _rows(
        loaded, "SELECT id, status FROM recon.reconciliation_runs WHERE ruleset_version = 'v2'"
    )
    assert status == "failed"
    assert _rows(
        loaded,
        "SELECT (SELECT count(*) FROM recon.match_groups WHERE run_id = :r),"
        " (SELECT count(*) FROM recon.match_group_members WHERE run_id = :r),"
        " (SELECT count(*) FROM recon.discrepancies WHERE run_id = :r),"
        " (SELECT count(*) FROM recon.outbox)",
        r=run_id,
    ) == [(0, 0, 0, 41)]  # the outbox holds only the first run's events


def test_the_database_rejects_a_record_in_two_match_groups_of_one_run(loaded: Engine) -> None:
    run = _reconcile(loaded)(OCTOBER)
    [(payment_id,)] = _rows(
        loaded,
        "SELECT payment_id FROM recon.match_group_members WHERE payment_id IS NOT NULL LIMIT 1",
    )
    group_id = uuid.uuid4()
    with (
        pytest.raises(IntegrityError, match="match_group_members_run_id_payment_id_key"),
        loaded.begin() as connection,
    ):
        connection.execute(
            text("INSERT INTO recon.match_groups VALUES (:g, :r, 'manual')"),
            {"g": group_id, "r": run.id},
        )
        connection.execute(
            text(
                "INSERT INTO recon.match_group_members (group_id, run_id, role, payment_id)"
                " VALUES (:g, :r, 'payment', :p)"
            ),
            {"g": group_id, "r": run.id, "p": payment_id},
        )


def test_the_database_rejects_overlapping_fee_schedule_periods(loaded: Engine) -> None:
    with (
        pytest.raises(IntegrityError, match="fee_schedules_gateway_fee_type_valid_during_excl"),
        loaded.begin() as connection,
    ):
        connection.execute(
            text(
                "INSERT INTO recon.fee_schedules"
                " (id, gateway, fee_type, rate_bps, fixed_minor, currency, valid_during)"
                " VALUES (gen_random_uuid(), 'gateway_a', 'processing', 300, 30, 'USD',"
                " '[2026-06-01,2026-07-01)')"
            )
        )
    # an adjacent half-open period of the same gateway, and another gateway, do not overlap
    with loaded.begin() as connection:
        connection.execute(
            text(
                "INSERT INTO recon.fee_schedules"
                " (id, gateway, fee_type, rate_bps, fixed_minor, currency, valid_during)"
                " VALUES (gen_random_uuid(), 'gateway_a', 'processing', 300, 30, 'USD',"
                " '[2025-01-01,2026-01-01)'),"
                " (gen_random_uuid(), 'gateway_c', 'processing', 300, 30, 'USD',"
                " '[2026-06-01,2026-07-01)')"
            )
        )
    assert _rows(loaded, "SELECT count(*) FROM recon.fee_schedules") == [(4,)]


def test_the_database_keeps_one_live_run_per_period_and_ruleset(engine: Engine) -> None:
    insert = text(
        "INSERT INTO recon.reconciliation_runs"
        " (id, period, ruleset_version, status, started_at, finished_at)"
        " VALUES (gen_random_uuid(), '[2026-10-01,2026-11-01)', 'v1', :status, now(), :finished)"
    )
    with engine.begin() as connection:  # failed runs stay for the record, any number of them
        for _ in range(2):
            connection.execute(insert, {"status": "failed", "finished": date(2026, 11, 1)})
        connection.execute(insert, {"status": "running", "finished": None})
    with (
        pytest.raises(IntegrityError, match="reconciliation_runs_live_key"),
        engine.begin() as connection,
    ):
        connection.execute(insert, {"status": "completed", "finished": date(2026, 11, 1)})
