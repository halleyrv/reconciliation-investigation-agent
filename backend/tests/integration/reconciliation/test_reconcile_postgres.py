OCTOBER = Period(date(2026, 10, 1), date(2026, 10, 31))
REFERENCE_FILE = Path(__file__).parents[3] / "reference" / "gateway-policy-2026.json"


def _rows(engine: Engine, sql: str, **params: object) -> list[tuple[object, ...]]:
    with engine.connect() as connection:
        return [tuple(r) for r in connection.execute(text(sql), params)]


@pytest.fixture
def loaded(engine: Engine, sample: Path) -> Engine:
    uow = SqlAlchemyIngestionUnitOfWork(sessionmaker(engine))
    ImportExport(uow, SystemClock(), UuidIdGenerator())(read_export(sample))
    reference = SqlAlchemyReconciliationUnitOfWork(sessionmaker(engine))
    LoadReferenceData(reference, UuidIdGenerator())(*read_reference_file(REFERENCE_FILE))
    return engine


def _reconcile(engine: Engine) -> ReconcilePeriod:
    uow = SqlAlchemyReconciliationUnitOfWork(sessionmaker(engine))
    return ReconcilePeriod(uow, SystemClock(), UuidIdGenerator())


def test_reconciling_the_sample_persists_every_discrepancy_group_and_event(loaded: Engine) -> None:
    run = _reconcile(loaded)(OCTOBER)

    assert run.status is RunStatus.COMPLETED
    [(status, period)] = _rows(loaded, "SELECT status, period::text FROM recon.reconciliation_runs")
    assert (status, period) == ("completed", "[2026-10-01,2026-11-01)")
    by_type = {
        t: n
        for t, n in _rows(loaded, "SELECT type, count(*) FROM recon.discrepancies GROUP BY type")
    }
    assert sum(int(str(n)) for n in by_type.values()) == 41
    assert by_type["missing_in_bank"] == 1 and by_type["duplicate_refund"] == 4
    assert _rows(
        loaded, "SELECT count(*) FROM recon.outbox WHERE event_type = 'DiscrepancyDetected'"
    ) == [(41,)]
    # delta is generated by the database from expected and actual
    assert _rows(
        loaded,
        "SELECT count(*) FROM recon.discrepancies d"
        " JOIN ref.discrepancy_types t ON t.code = d.type AND d.severity = t.default_severity"
        " WHERE d.delta_minor = d.actual_minor - d.expected_minor",
    ) == [(41,)]
    [(orders_linked,)] = _rows(
        loaded, "SELECT count(*) FROM recon.match_group_members WHERE order_id IS NOT NULL"
    )
    assert orders_linked == 158


def test_reconciling_again_returns_the_run_and_creates_nothing(loaded: Engine) -> None:
    first = _reconcile(loaded)(OCTOBER)
    counts = (
        "SELECT (SELECT count(*) FROM recon.match_groups),"
        " (SELECT count(*) FROM recon.discrepancies)"
    )
    fingerprints = "SELECT fingerprint FROM recon.discrepancies ORDER BY fingerprint"
    before = (_rows(loaded, counts), _rows(loaded, fingerprints))

    again = _reconcile(loaded)(OCTOBER)

    assert again == first
    assert (_rows(loaded, counts), _rows(loaded, fingerprints)) == before
    assert _rows(loaded, "SELECT count(*) FROM recon.reconciliation_runs") == [(1,)]


def test_a_run_failing_halfway_is_failed_with_no_groups_or_discrepancies(loaded: Engine) -> None:
    # A trigger rejects the run's 20th discrepancy, after every match group was written.
    with loaded.begin() as connection:
        connection.execute(
            text(
                "CREATE FUNCTION recon.fail_halfway() RETURNS trigger LANGUAGE plpgsql AS $$"
                " BEGIN IF (SELECT count(*) FROM recon.discrepancies) >= 19 THEN"
                " RAISE EXCEPTION 'injected failure halfway'; END IF; RETURN NEW; END $$;"
                " CREATE TRIGGER fail_halfway BEFORE INSERT ON recon.discrepancies"
                " FOR EACH ROW EXECUTE FUNCTION recon.fail_halfway();"
            )
        )
    try:
        with pytest.raises(RunFailed, match="injected failure halfway"):
            _reconcile(loaded)(OCTOBER)
    finally:
        with loaded.begin() as connection:
            connection.execute(
                text(
                    "DROP TRIGGER fail_halfway ON recon.discrepancies;"
                    " DROP FUNCTION recon.fail_halfway();"
                )
            )

    [(run_id, status)] = _rows(loaded, "SELECT id, status FROM recon.reconciliation_runs")
    assert status == "failed"
    assert _rows(
        loaded,
        "SELECT (SELECT count(*) FROM recon.match_groups WHERE run_id = :r),"
        " (SELECT count(*) FROM recon.match_group_members WHERE run_id = :r),"
        " (SELECT count(*) FROM recon.discrepancies WHERE run_id = :r),"
        " (SELECT count(*) FROM recon.outbox)",
        r=run_id,
    ) == [(0, 0, 0, 0)]
    assert _reconcile(loaded)(OCTOBER).status is RunStatus.COMPLETED  # the retry is clean


def _comparable(f: Finding) -> tuple[str, tuple[tuple[str, str], ...], int]:
    return f.type, tuple(sorted(f.records)), f.delta_minor


def test_a_month_split_in_two_halves_reports_exactly_what_the_whole_month_reports(
    loaded: Engine,
) -> None:
    whole = _reconcile(loaded)(OCTOBER)
    first = _reconcile(loaded)(Period(date(2026, 10, 1), date(2026, 10, 15)), "halves")
    second = _reconcile(loaded)(Period(date(2026, 10, 16), date(2026, 10, 31)), "halves")

    uow = SqlAlchemyReconciliationUnitOfWork(sessionmaker(loaded))
    with uow:
        month = sorted(map(_comparable, uow.outputs.findings(whole.id)))
        halves = [sorted(map(_comparable, uow.outputs.findings(run.id))) for run in (first, second)]
        links = [uow.outputs.links(run.id) for run in (whole, first, second)]
    assert halves[0] and halves[1]
    assert sorted(halves[0] + halves[1]) == month
    assert not links[1] & links[2] and links[1] | links[2] == links[0]


def test_a_run_without_reference_data_fails_and_succeeds_once_it_is_loaded(
    engine: Engine, sample: Path
) -> None:
    uow = SqlAlchemyIngestionUnitOfWork(sessionmaker(engine))
    ImportExport(uow, SystemClock(), UuidIdGenerator())(read_export(sample))

    with pytest.raises(RunFailed, match="no bank holiday calendar for 2026"):
        _reconcile(engine)(OCTOBER)
    reference = SqlAlchemyReconciliationUnitOfWork(sessionmaker(engine))
    LoadReferenceData(reference, UuidIdGenerator())(*read_reference_file(REFERENCE_FILE))

    assert _reconcile(engine)(OCTOBER).status is RunStatus.COMPLETED
    assert _rows(engine, "SELECT status FROM recon.reconciliation_runs ORDER BY started_at") == [
        ("failed",),
        ("completed",),
    ]


def test_the_database_rejects_a_record_in_two_match_groups_of_one_run(loaded: Engine) -> None:
    run = _reconcile(loaded)(OCTOBER)
    [(payment_id,)] = _rows(
        loaded,
        "SELECT payment_id FROM recon.match_group_members WHERE payment_id IS NOT NULL LIMIT 1",
    )
    group_id = uuid.uuid4()
    with (
        pytest.raises(IntegrityError, match="match_group_members_run_id_payment_id_key"),
        loaded.begin() as connection,
    ):
        connection.execute(
            text("INSERT INTO recon.match_groups VALUES (:g, :r, 'manual')"),
            {"g": group_id, "r": run.id},
        )
        connection.execute(
            text(
                "INSERT INTO recon.match_group_members (group_id, run_id, role, payment_id)"
                " VALUES (:g, :r, 'payment', :p)"
            ),
            {"g": group_id, "r": run.id, "p": payment_id},
        )


def test_the_database_rejects_overlapping_fee_schedule_periods(loaded: Engine) -> None:
    with (
        pytest.raises(IntegrityError, match="fee_schedules_gateway_fee_type_valid_during_excl"),
        loaded.begin() as connection,
    ):
        connection.execute(
            text(
                "INSERT INTO recon.fee_schedules"
                " (id, gateway, fee_type, rate_bps, fixed_minor, currency, valid_during)"
                " VALUES (gen_random_uuid(), 'gateway_a', 'processing', 300, 30, 'USD',"
                " '[2026-06-01,2026-07-01)')"
            )
        )
    # an adjacent half-open period of the same gateway, and another gateway, do not overlap
    with loaded.begin() as connection:
        connection.execute(
            text(
                "INSERT INTO recon.fee_schedules"
                " (id, gateway, fee_type, rate_bps, fixed_minor, currency, valid_during)"
                " VALUES (gen_random_uuid(), 'gateway_a', 'processing', 300, 30, 'USD',"
                " '[2025-01-01,2026-01-01)'),"
                " (gen_random_uuid(), 'gateway_c', 'processing', 300, 30, 'USD',"
                " '[2026-06-01,2026-07-01)')"
            )
        )
    assert _rows(loaded, "SELECT count(*) FROM recon.fee_schedules") == [(4,)]


def test_the_database_keeps_live_runs_of_one_ruleset_from_sharing_a_day(engine: Engine) -> None:
    insert = text(
        "INSERT INTO recon.reconciliation_runs"
        " (id, period, ruleset_version, status, started_at, finished_at)"
        " VALUES (gen_random_uuid(), '[2026-10-01,2026-11-01)', 'v1', :status, now(), :finished)"
    )
    with engine.begin() as connection:  # failed runs stay for the record, any number of them
        for _ in range(2):
            connection.execute(insert, {"status": "failed", "finished": date(2026, 11, 1)})
        connection.execute(insert, {"status": "running", "finished": None})
    with (
        pytest.raises(IntegrityError, match="reconciliation_runs_live_period_excl"),
        engine.begin() as connection,
    ):
        connection.execute(insert, {"status": "completed", "finished": date(2026, 11, 1)})
    overlapping = text(
        "INSERT INTO recon.reconciliation_runs"
        " (id, period, ruleset_version, status, started_at)"
        " VALUES (gen_random_uuid(), :period, :ruleset, 'running', now())"
    )
    with (
        pytest.raises(IntegrityError, match="reconciliation_runs_live_period_excl"),
        engine.begin() as connection,
    ):
        connection.execute(overlapping, {"period": "[2026-10-31,2026-12-01)", "ruleset": "v1"})
    with engine.begin() as connection:  # adjacent periods and other rulesets are fine
        connection.execute(overlapping, {"period": "[2026-11-01,2026-12-01)", "ruleset": "v1"})
        connection.execute(overlapping, {"period": "[2026-10-15,2026-11-15)", "ruleset": "v2"})


def test_concurrent_reconciles_of_one_period_create_one_run(loaded: Engine) -> None:
    barrier = threading.Barrier(2)

    def reconcile() -> str:
        barrier.wait()
        try:
            return _reconcile(loaded)(OCTOBER).status.value
        except RunInProgress:
            return "in progress"

    with ThreadPoolExecutor(2) as pool:
        outcomes = sorted(pool.map(lambda _: reconcile(), range(2)))

    assert outcomes in (["completed", "completed"], ["completed", "in progress"])
    assert _rows(loaded, "SELECT count(*) FROM recon.reconciliation_runs") == [(1,)]
    assert _rows(loaded, "SELECT count(*) FROM recon.discrepancies") == [(41,)]


def test_concurrent_overlapping_periods_leave_one_live_run_and_a_clear_refusal(
    loaded: Engine,
) -> None:
    barrier = threading.Barrier(2)
    periods = [
        Period(date(2026, 10, 1), date(2026, 10, 20)),
        Period(date(2026, 10, 10), date(2026, 10, 31)),
    ]

    def reconcile(period: Period) -> str:
        barrier.wait()
        try:
            return _reconcile(loaded)(period).status.value
        except PeriodOverlaps:
            return "overlaps"

    with ThreadPoolExecutor(2) as pool:
        outcomes = sorted(pool.map(reconcile, periods))

    assert outcomes == ["completed", "overlaps"]
